"""Pin every parameter the documentation quotes.

`docs/scope-and-limitations.md` §5 maps each documented construction to a
code symbol and to a test below.  If the implementation and a note drift
apart, one of these tests fails, which is the point: the notes are allowed to
have limitations, but they are not allowed to describe code that does not
exist.
"""

import numpy as np
import pytest

from modcode.channel.multipath import MultipathChannel, TapProcess
from modcode.channel.rayleigh import BlockRayleighChannel
from modcode.fec.ldpc import LDPC36
from modcode.fec.polar import PolarAWGN
from modcode.modulation.qpsk import QPSK
from modcode.pipeline.ofdm import OFDMLink


def test_ldpc_block_structure():
    """ldpc.md §1: block size 84, six block rows, twelve block columns."""
    code = LDPC36()
    assert code.block_size == 84
    assert code.block_rows == 6
    assert code.block_columns == 12
    assert code.n == 1008
    assert code.m == 504


def test_ldpc_block_dimensions():
    """ldpc.md §1: rank 502, k 506, rate 506/1008."""
    code = LDPC36()
    assert code.rank == 502
    assert code.data_bits_per_block == 506
    assert code.encoded_bits_per_block == 1008
    assert code.rate == pytest.approx(506.0 / 1008.0, abs=1e-12)


def test_ldpc_is_regular_three_six():
    """ldpc.md §1: every variable has degree 3 and every check degree 6."""
    code = LDPC36()
    assert code.H.shape == (504, 1008)
    assert set(np.count_nonzero(code.H, axis=0).tolist()) == {3}
    assert set(np.count_nonzero(code.H, axis=1).tolist()) == {6}
    assert int(np.count_nonzero(code.H)) == 3024


def test_ldpc_decoder_defaults():
    """ldpc.md §2: normalized min-sum with alpha 0.8 and 50 iterations."""
    code = LDPC36()
    assert code.alpha == pytest.approx(0.8, abs=1e-12)
    assert code.max_iterations == 50


def test_polar_block_and_crc():
    """polar.md §1: N 1024, k 512, CRC-8 generated by x^8 + x^2 + x + 1."""
    code = PolarAWGN()
    assert code.block_length == 1024
    assert code.data_bits_per_block == 512
    assert code.rate == pytest.approx(0.5, abs=1e-12)
    assert code.crc is not None
    assert code.crc.width == 8
    # The implicit leading x^8 is not stored, so 0x07 is x^8 + x^2 + x + 1.
    assert code.crc.polynomial == 0x07


def test_polar_decoder_defaults():
    """polar.md §1 and §4: list size 4, Gaussian design at 2 dB."""
    code = PolarAWGN()
    assert code.list_size == 4
    assert code.design_ebn0_db == pytest.approx(2.0, abs=1e-12)


def test_ofdm_defaults():
    """multipath.md §2: 64 subcarriers, pilot spacing 4, least squares."""
    link = OFDMLink(
        modulation=QPSK(),
        channel=TapProcess((0.7, 0.3)),
        delays=(0, 1),
    )
    assert link.n_fft == 64
    assert link.pilot_spacing == 4
    assert link.estimation == "ls"
    assert len(link.pilot_subcarriers) == 16


def test_multipath_defaults():
    """multipath.md §1: taps (0.7, 0.3), delays (0, 1), 16 sinusoids."""
    channel = MultipathChannel()
    assert channel.delays == (0, 1)
    assert channel.process.taps_count == 2
    assert channel.process.powers == pytest.approx([0.7, 0.3])


def test_rayleigh_block_length():
    """advanced-coding.md §2: one coefficient per 10-symbol block, repeated."""
    channel = BlockRayleighChannel(block_length=10)
    assert channel.block_length == 10
    assert channel.equalize is True
    symbols = np.ones(30, dtype=np.complex128)
    channel.transmit(symbols, 0.1, np.random.default_rng(0))
    coefficients = channel.last_coefficients
    assert coefficients is not None
    assert coefficients.size == symbols.size
    for start in range(0, symbols.size, 10):
        block = coefficients[start : start + 10]
        assert np.allclose(block, block[0])
    assert not np.allclose(coefficients[0], coefficients[10])
